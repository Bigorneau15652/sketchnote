# Build tool, not shipped with the plugin: reduces the four handwritten fonts to the latin letters and writes src/fonts-builtin.ts (WOFF2 in base 64).
# Usage: python3 tools/make-fonts.py DIR  where DIR holds the files downloaded from https://github.com/google/fonts (folder ofl). Needs fonttools and brotli (MIT).
import base64, io, sys
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

SOURCES = [
    ("caveat", "Caveat", "caveat_Caveat[wght].ttf"),
    ("patrick-hand", "Patrick Hand", "patrickhand_PatrickHand-Regular.ttf"),
    ("gloria-hallelujah", "Gloria Hallelujah", "gloriahallelujah_GloriaHallelujah.ttf"),
    ("architects-daughter", "Architects Daughter", "architectsdaughter_ArchitectsDaughter-Regular.ttf"),
]
# Basic latin, Latin-1, Latin extended A, typographic punctuation, euro, a few arrows and signs.
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x2010, 0x2027), (0x20AC, 0x20AC), (0x2190, 0x2193), (0x2212, 0x2212), (0x00B0, 0x00B0), (0x2022, 0x2022)]

def main(folder):
    out = []
    for ident, name, file in SOURCES:
        font = TTFont(f"{folder}/{file}")
        if "fvar" in font:
            font = instancer.instantiateVariableFont(font, {"wght": 400})
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = ["*"]
        opts.name_IDs = [1, 2, 3, 4, 6]
        opts.notdef_outline = True
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=[c for a, b in RANGES for c in range(a, b + 1)])
        sub.subset(font)
        buf = io.BytesIO()
        font.flavor = "woff2"
        font.save(buf)
        out.append((ident, name, base64.b64encode(buf.getvalue()).decode("ascii")))
        print(ident, len(buf.getvalue()), file=sys.stderr)
    lines = [
        "// Generated by tools/make-fonts.py: four handwritten fonts under the SIL Open Font License 1.1 (texts in licences/), reduced to the latin letters, as WOFF2 in base 64.",
        "export interface BuiltinFont {",
        "  id: string;",
        "  name: string;",
        "  data: string;",
        "}",
        "",
        "export const BUILTIN_FONTS: BuiltinFont[] = [",
    ]
    for ident, name, data in out:
        lines.append(f"  {{ id: `{ident}`, name: `{name}`, data: `{data}` }},")
    lines.append("];")
    open("src/fonts-builtin.ts", "w", encoding="utf8").write("\n".join(lines) + "\n")

main(sys.argv[1])
